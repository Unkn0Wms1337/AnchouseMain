    inline bool IsExtra(std::uint32_t Def)
    {
        std::size_t Low = 0;
        std::size_t High = sizeof(ExtraDefs) / sizeof(ExtraDefs[0]);
        while (Low < High)
        {
            const std::size_t Mid = Low + (High - Low) / 2;
            if (ExtraDefs[Mid] < Def)
                Low = Mid + 1;
            else
                High = Mid;
        }
        return Low < sizeof(ExtraDefs) / sizeof(ExtraDefs[0]) && ExtraDefs[Low] == Def;
    }
